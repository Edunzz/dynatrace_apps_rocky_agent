// Gateway configuration, read once from the environment.
// Secret values are kept in this object only; they are never logged.

const DEFAULT_PASSWORD = "edunzzxgundam79";

function intFromEnv(env, name, fallback, { min = 1, max = Number.MAX_SAFE_INTEGER } = {}) {
  const raw = env[name];
  if (raw === undefined || raw === "") return fallback;
  const value = Number.parseInt(raw, 10);
  if (!Number.isInteger(value) || value < min || value > max) {
    throw new Error(`${name} must be an integer between ${min} and ${max}`);
  }
  return value;
}

function boolFromEnv(env, name, fallback) {
  const raw = env[name];
  if (raw === undefined || raw === "") return fallback;
  return ["1", "true", "yes", "on"].includes(String(raw).toLowerCase());
}

export function parseAllowedOrigins(raw) {
  if (!raw) return [];
  return raw
    .split(",")
    .map((origin) => origin.trim())
    .filter(Boolean);
}

export function loadConfig(env = process.env) {
  const password = env.OPENCODE_SERVER_PASSWORD ?? "";
  if (!password) {
    throw new Error("OPENCODE_SERVER_PASSWORD is required");
  }
  return {
    listenHost: env.ROCKY_GATEWAY_HOST || "0.0.0.0",
    listenPort: intFromEnv(env, "OPENCODE_PORT", 4096, { max: 65535 }),
    upstreamHost: env.OPENCODE_INTERNAL_HOST || "127.0.0.1",
    upstreamPort: intFromEnv(env, "OPENCODE_INTERNAL_PORT", 4097, { max: 65535 }),
    username: env.OPENCODE_SERVER_USERNAME || "opencode",
    password,
    usesDefaultPassword: password === DEFAULT_PASSWORD,
    // The loopback OpenCode server uses its own random password, generated by
    // the entrypoint, so the client password never reaches agent processes.
    upstreamUsername: env.ROCKY_UPSTREAM_USERNAME || env.OPENCODE_SERVER_USERNAME || "opencode",
    upstreamPassword: env.ROCKY_UPSTREAM_PASSWORD || password,
    nodeEnv: env.NODE_ENV || "production",
    logLevel: (env.LOG_LEVEL || "info").toLowerCase(),
    allowedOrigins: parseAllowedOrigins(env.ALLOWED_ORIGINS),
    consoleEnabled: boolFromEnv(env, "ROCKY_CONSOLE_ENABLED", false),
    maxBodyBytes: intFromEnv(env, "ROCKY_MAX_BODY_BYTES", 1024 * 1024),
    upstreamTimeoutMs: intFromEnv(env, "ROCKY_UPSTREAM_TIMEOUT_MS", 60_000),
    stateDir: env.ROCKY_STATE_DIR || "/tmp/rocky",
    policyFile: env.ROCKY_POLICY_FILE || "/opt/rocky/policy/AGENTS.md",
    validateDynatraceScript:
      env.ROCKY_VALIDATE_DYNATRACE_SCRIPT || "/opt/rocky/scripts/validate-dynatrace.sh",
    workspacePath: env.WORKSPACE_PATH || "/workspace",
    runtimeVersion: env.ROCKY_VERSION || "0.0.0-dev",
    provider: env.OPENCODE_PROVIDER || "",
    model: env.OPENCODE_MODEL || "",
    dynatraceUrl: env.DT_PLATFORM_URL || "",
  };
}

export { DEFAULT_PASSWORD };
